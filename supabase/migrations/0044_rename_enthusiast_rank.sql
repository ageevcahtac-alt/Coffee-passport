-- =========================================================
-- Ренейм ранга 6 лестницы «Зал»: «Энтузиаст» → «Кофейный энтузиаст»
--
-- UPDATE существующей строки на проде (идентификатор ранга не меняется,
-- порог/кэшбэк/цвет — прежние). Идемпотентно: повторный прогон находит
-- ноль строк «Энтузиаст» и не делает ничего. Названия остальных рангов
-- не трогаем.
--
-- В следующем этапе этот ранг будет продаваться за 5 000 ₽ — все
-- упоминания покупки обязаны использовать новое имя.
--
-- Применение: workflow db-migrate (ручной запуск) — см. CLAUDE.md.
-- Проверка: SELECT rank_order, rank_name FROM public.shop_ranks
--   WHERE shop_id = 'shop-xo-vsevolozhsk' AND circuit = 'hall' ORDER BY rank_order;
-- =========================================================

update public.shop_ranks
set rank_name = 'Кофейный энтузиаст',
    updated_at = now()
where shop_id = 'shop-xo-vsevolozhsk'
  and circuit = 'hall'
  and rank_name = 'Энтузиаст';
